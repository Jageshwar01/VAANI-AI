"""
VaaniAI — Interview Report Generator
Generates professional interview summary reports saved to data/reports/.
"""

import os
from datetime import datetime
from app.config import REPORTS_DIR


class ReportGenerator:
    """
    Generates a professional text-based interview report.
    Saved to data/reports/ as a .txt file for easy reading.
    """

    def __init__(self):
        os.makedirs(REPORTS_DIR, exist_ok=True)

    def generate(
        self,
        interview_id: int,
        candidate_name: str,
        interview_type: str,
        start_time: str,
        end_time: str,
        questions_data: list[dict],
        total_score: float,
    ) -> str:
        """
        Generate and save a full interview report.
        
        Args:
            interview_id: Database interview ID
            candidate_name: Name of the candidate
            interview_type: Type of interview (general/python/etc.)
            start_time: ISO format start time
            end_time: ISO format end time
            questions_data: List of dicts with keys: question, answer, score, feedback, grade
            total_score: Average total score
        
        Returns:
            Path to the saved report file.
        """
        # Build report content
        report = []
        report.append("=" * 60)
        report.append("       VAANIAI - INTERVIEW PERFORMANCE REPORT")
        report.append("=" * 60)
        report.append("")
        report.append(f"  Candidate Name  : {candidate_name}")
        report.append(f"  Interview Type  : {interview_type.title()}")
        report.append(f"  Interview ID    : #{interview_id}")
        report.append(f"  Date            : {self._format_date(start_time)}")
        report.append(f"  Duration        : {self._calc_duration(start_time, end_time)}")
        report.append(f"  Total Questions : {len(questions_data)}")
        report.append(f"  Average Score   : {total_score:.1f} / 10.0")
        report.append(f"  Overall Grade   : {self._score_to_grade(total_score)}")
        report.append(f"  Result          : {'PASSED' if total_score >= 5.0 else 'NEEDS IMPROVEMENT'}")
        report.append("")
        report.append("-" * 60)
        report.append("  QUESTION-WISE BREAKDOWN")
        report.append("-" * 60)

        for i, qd in enumerate(questions_data, 1):
            report.append("")
            report.append(f"  Q{i}. {qd.get('question', 'N/A')}")
            report.append(f"  Answer  : {qd.get('answer', 'No answer provided')[:200]}")
            report.append(f"  Score   : {qd.get('score', 0):.1f}/10  |  Grade: {qd.get('grade', 'N/A')}")
            report.append(f"  Feedback: {qd.get('feedback', 'N/A')}")
            report.append(f"  {'─' * 50}")

        report.append("")
        report.append("-" * 60)
        report.append("  OVERALL ASSESSMENT")
        report.append("-" * 60)
        report.append("")

        if total_score >= 8.0:
            report.append("  Outstanding performance! The candidate demonstrated")
            report.append("  excellent knowledge and communication skills.")
        elif total_score >= 6.5:
            report.append("  Good performance. The candidate shows solid")
            report.append("  understanding with room for improvement in some areas.")
        elif total_score >= 5.0:
            report.append("  Average performance. The candidate needs to work on")
            report.append("  providing more detailed and structured answers.")
        elif total_score >= 3.5:
            report.append("  Below average. The candidate should focus on building")
            report.append("  stronger fundamentals and communication skills.")
        else:
            report.append("  Needs significant improvement. The candidate should")
            report.append("  prepare more thoroughly for future interviews.")

        report.append("")
        report.append("=" * 60)
        report.append("  Report generated by VaaniAI Interview System")
        report.append(f"  Generated at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
        report.append("=" * 60)

        # Save to file
        report_text = "\n".join(report)
        safe_name = candidate_name.replace(" ", "_").lower()
        filename = f"interview_{safe_name}_{interview_id}.txt"
        filepath = os.path.join(REPORTS_DIR, filename)

        with open(filepath, "w", encoding="utf-8") as f:
            f.write(report_text)

        print(f"[REPORT] Saved: {filepath}")
        return filepath

    def _format_date(self, iso_time: str) -> str:
        """Format ISO time to readable date."""
        try:
            dt = datetime.fromisoformat(iso_time)
            return dt.strftime("%B %d, %Y at %I:%M %p")
        except Exception:
            return iso_time

    def _calc_duration(self, start: str, end: str) -> str:
        """Calculate interview duration."""
        try:
            s = datetime.fromisoformat(start)
            e = datetime.fromisoformat(end)
            diff = e - s
            minutes = int(diff.total_seconds() // 60)
            seconds = int(diff.total_seconds() % 60)
            return f"{minutes} min {seconds} sec"
        except Exception:
            return "N/A"

    @staticmethod
    def _score_to_grade(score: float) -> str:
        if score >= 9.0:
            return "A+"
        elif score >= 8.0:
            return "A"
        elif score >= 7.0:
            return "B+"
        elif score >= 6.0:
            return "B"
        elif score >= 5.0:
            return "C"
        elif score >= 4.0:
            return "D"
        return "F"
